def _launch_error_message(error_code: int, requested_block_dim: int, compiled: "CompiledKernel | None") -> str:
    """Decode the native -(kind << 32 | detail) launch error into a readable message.

    The raw code stays in the message for log grepping; the appended text explains
    the rejection in terms the caller can act on. ``requested_block_dim`` is the
    value handed to the launcher (0 only for the auto sentinel, which is never
    rejected as an over-budget request).
    """
    code = -int(error_code)
    kind, detail = code >> 32, code & 0xFFFFFFFF
    prefix = f"Kernel launch failed with error code {error_code}"
    if kind == 5:
        return f"{prefix}: requested block_dim {requested_block_dim} exceeds the stream budget of {detail} block(s)"
    if kind in (1, 2):
        engine = "cube" if kind == 1 else "vector"
        target = getattr(compiled, "target", None)
        per_block = (target.aic_per_block if kind == 1 else target.aiv_per_block) if target else 0
        if per_block:
            return (
                f"{prefix}: the stream's {engine} budget of {detail} core(s) cannot host one block "
                f"of {per_block} {engine} core(s)"
            )
        return f"{prefix}: the stream's {engine} budget of {detail} core(s) cannot host one block"
    if kind in (3, 4):
        engine = "cube" if kind == 3 else "vector"
        return f"{prefix}: querying the stream's {engine} budget failed with ACL error {detail:#x}"
    return f"{prefix} (kind={kind}, detail={detail:#x})"


def _launch(compiled: "CompiledKernel", args: tuple, block_dim: int, stream):
    """Launch one compiled kernel, binding its entry closure on first use.

    Kept as a module-level function rather than inlined into the launcher so test
    infrastructure has a single seam to stub out (see the PARALLEL_COMPILE conftest,
    which replaces this to discover kernels without touching the device). ``args`` is
    passed as a tuple, not ``*args``, so the hot path does not rebuild it.
    """
    entry = compiled.entry
    if entry is None:
        entry = compiled.entry = _build_launch_entry(compiled)
    entry(args, block_dim, stream)


def _format_findings(findings) -> str:
    """One block of human-readable findings (or the clean-run marker).

    Multi-line findings (message + Hint) are indented to the kind column so
    the Hint lines up with the leading G of GM_OUT_OF_BOUNDS et al.
    """
    if not findings:
        return "PyPTO Sanitizer: no issues detected\n"
    lines = [f"PyPTO Sanitizer: {len(findings)} issue(s) detected\n"]
    for i, finding in enumerate(findings, 1):
        prefix = f"[{i}/{len(findings)}] "
        pad = " " * len(prefix)
        for j, line in enumerate(str(finding).split("\n")):
            lines.append(f"{prefix}{line}\n" if j == 0 else f"{pad}{line}\n")
    return "".join(lines)


def _replay_sanitizer(log_buffer, capacity_u32, block_dim, build_dir, kernel_name, source_file):
    """Wait for the launch, read the written part of the device log buffer
    back, merge it with the compile-time metadata into one
    ``sanitizer_report.bin``, scan that file with the registered detections
    and raise an aggregated report when findings exist.

    Results go to pypto_sanitizer_report.txt next to sanitizer_report.bin in
    the kernel's build dir (one file per compile instance), appended per
    launch (kernel-tagged). No terminal output; an uncaught
    SanitizerReplayError is the only on-screen signal.

    Replay failures are never swallowed: when the sanitizer is enabled the
    developer expects the detection result to be trustworthy, so a broken
    decode or check must surface instead of silently producing a "clean"
    result.
    """
    from pypto_pro.runtime.sanitizer_replay import SanitizerReplayError, build_report_file, scan_report_file

    torch.npu.synchronize()
    words_per_region = capacity_u32 + 1
    flat = log_buffer.view(torch.int32)
    # Lazy copy-back stage 1: the per-region write counters only.
    ctrs = flat[::words_per_region].cpu().tolist()
    # Stage 2: for each region copy back just the ctr word and the records
    # actually written (a region that never executed copies one word).
    region_chunks = []
    for region_idx, ctr in enumerate(ctrs):
        written = min(int(ctr), capacity_u32)
        start = region_idx * words_per_region
        region_chunks.append(flat[start:start + 1 + written].cpu().numpy().tobytes())
    report_path = os.path.join(build_dir, "sanitizer_report.bin")
    build_report_file(region_chunks, report_path)
    findings = scan_report_file(report_path, source_file)
    # Detection result file, appended per launch (kernel-tagged), next to
    # sanitizer_report.bin in the build dir.
    report_file = os.path.join(build_dir, "pypto_sanitizer_report.txt")
    with open(report_file, "a", encoding="utf-8") as f:
        f.write(f"===== kernel '{kernel_name}' ({build_dir}) =====\n")
        f.write(_format_findings(findings))
        f.write("\n")
    if findings:
        raise SanitizerReplayError(findings)


def _validate_block_dim(block_dim):
    """Validate that block_dim is a positive integer.

    Raises ValueError if block_dim is not an int or is <= 0.
    """
    if not isinstance(block_dim, int) or isinstance(block_dim, bool):
        raise InvalidType(
            f"block_dim must be a positive integer, got {type(block_dim).__name__}: {block_dim}"
        )
    if block_dim <= 0:
        raise InvalidType(
            f"block_dim must be a positive integer, got {block_dim}"
        )


# block_dim handed to the native launcher when the caller did not pick a core
# count (direct kernel call); the native side resolves it to the stream's full
# block budget (kAutoBlockDim in pypto_launch.h). Bracket-launch input is
# validated positive by _validate_block_dim and saturated before the ABI, so a
# user-supplied 0 cannot reach this protocol.
_AUTO_BLOCK_DIM = 0


def _auto_block_upper_bound(compiled: "CompiledKernel") -> int:
    """Device-level upper bound on the auto-resolved block count, used to size
    host resources (the sanitizer log buffer) before the native launch resolves
    the sentinel; it can over-estimate, never under-estimate."""
    from pypto_pro.runtime.platform import get_platform_info

    info = get_platform_info()
    target = compiled.target
    if target is not None and info.core_num > 0:
        blocks = []
        if target.aic_per_block:
            blocks.append(info.cube_core_num // target.aic_per_block)
        if target.aiv_per_block:
            blocks.append(info.vector_core_num // target.aiv_per_block)
        if blocks and min(blocks) > 0:
            return min(blocks)
    raise RuntimeError(
        "Cannot size per-block host resources for an auto block_dim launch: "
        "platform core counts are unavailable for this kernel"
    )


def _build_sanitizer_entry(compiled: "CompiledKernel", build_dir: str):
    """Wrap the launch entry of an instrumented kernel with the sanitizer glue.

    Keeps the upstream entry mechanism (``_build_launch_entry``) untouched:
    the base entry performs the ABI packing / validation / call, and this
    wrapper only (a) allocates the GM log buffer and appends the two hidden
    ``sanitizer_log``/``sanitizer_log_capacity`` arguments, then (b) reads the
    buffer back, merges it with the compile-time metadata into a single
    ``sanitizer_report.bin`` and scans that file with the registered
    detections.

    Loaded lazily on the first launch via ``compiled.entry``, exactly like the
    non-sanitizer path.
    """
    base_entry = _build_launch_entry(compiled)

    def entry(args: tuple, block_dim: int, stream):
        # The sentinel cannot size the buffer (the actual count is resolved
        # natively at launch); size by the device-level upper bound instead,
        # while the launch itself still carries the sentinel.
        sized_dim = _auto_block_upper_bound(compiled) if block_dim == _AUTO_BLOCK_DIM else block_dim
        regions = KSANITIZER_SUB_BLOCKS * sized_dim
        words_per_region = KSANITIZER_LOG_BUDGET_BYTES // (4 * regions)
        nbytes = words_per_region * 4 * regions
        log_buffer = torch.empty(nbytes, dtype=torch.uint8, device="npu")
        # Only the per-region ctr word must start at zero; the record area is
        # write-before-read on the device, so zeroing it would be wasted cost.
        log_buffer.view(torch.int32)[::words_per_region] = 0
        capacity_u32 = words_per_region - 1
        full_args = (*args, log_buffer, capacity_u32)
        base_entry(full_args, block_dim, stream)
        _replay_sanitizer(log_buffer, capacity_u32, sized_dim, build_dir, compiled.kernel_name, compiled.source_file)

    return entry


def _validate_tilingkey_no_var_conflict(f, tilingkey_schema, closure_vars):
    tilingkey_names = set(tilingkey_schema.field_names())

    param_names = set(f.__code__.co_varnames[:f.__code__.co_argcount])
    conflicts = tilingkey_names & param_names
    if conflicts:
        raise InvalidOperation(f"TilingKey field name(s) conflict with kernel parameter name(s): {conflicts}")

    non_builtin_names = set()
    for name, val in closure_vars.items():
        if name.startswith("__"):
            continue
        if callable(val) or isinstance(val, type):
            continue
        non_builtin_names.add(name)
    conflicts = tilingkey_names & non_builtin_names
    if conflicts:
        raise InvalidOperation(f"TilingKey field name(s) conflict with module-level variable name(s): {conflicts}")


def jit(
    target=None,
    *,
    arch: str | None = None,
    auto_mutex: bool = True,
    name: str | None = None,
    pipeline=None,
    tiling_key=None,
    datatype=None,
    compile_timeout: int | None = None,
    sanitizer: bool = False,
    **kwargs,
):
    """Mark a function for JIT compilation.

    When applied to a Tile-programming kernel (pl.Tensor parameters), the decorator
    performs lazy compilation on first call and supports bracket-launch syntax.

    Args:
        arch: Target architecture ("a5", or None for auto-detect).
        auto_mutex: Boolean flag to enable automatic mutex lock/unlock insertion.
        name: Custom kernel name for build artifact path isolation.
        pipeline: PipelineConfig for automatic preload pipeline transformation.
        compile_timeout: Compilation timeout in seconds (default 600).

    Usage (Tile-programming kernel with bracket-launch)::

        @pl.jit(arch="a5")
        def add_kernel(
            x: pl.Tensor[[64, 128], pl.DT_FP16],
            y: pl.Tensor[[64, 128], pl.DT_FP16],
            z: pl.Tensor[[64, 128], pl.DT_FP16]
        ) -> pl.Tensor[[64, 128], pl.DT_FP16]:
            ...

        add_kernel[stream, block_dim](x, y, z)
    """

    if not isinstance(auto_mutex, bool):
        raise TypeError(f"auto_mutex must be a bool, got {type(auto_mutex).__name__}")

    # Build the tilingkey schema eagerly so malformed schemas fail at decoration time.
    tilingkey_schema = None
    if tiling_key is not None:
        from pypto_pro.runtime.tilingkey import TilingKeySchema

        tilingkey_schema = TilingKeySchema(tiling_key)
    datatype_schema = _validate_datatype_schema(datatype)

    # Capture caller's scope for name resolution during lazy compilation.
    # Locals are snapshotted NOW (at decoration time) because a frame's locals
    # do not outlive the frame, but globals are kept as a LIVE reference so that
    # module-level helpers defined *below* the jit function are still resolvable
    # at compile time (compilation is lazy, on first call). Locals take priority
    # over globals, matching Python's own scoping.
    caller_frame = inspect.currentframe().f_back
    caller_closure_vars = ChainMap(dict(caller_frame.f_locals), caller_frame.f_globals)

    def decorator(f):
        if kwargs:
            raise InvalidArgument(
                f"jit() got unexpected keyword argument(s): {', '.join(kwargs.keys())}."
            )
        if tilingkey_schema is not None:
            _validate_tilingkey_no_var_conflict(f, tilingkey_schema, caller_closure_vars)

        # Detect if this is a Tile-programming kernel (has pl.Tensor annotations)
        # by checking if annotations contain type hints with shape/dtype info.
        is_tile_kernel = _is_tile_kernel(f)

        if is_tile_kernel:
            _validate_datatype_schema_context(datatype_schema, f, tilingkey_schema)
            return _TileJitKernel(
                func=f,
                arch=arch,
                auto_mutex=auto_mutex,
                name=name,
                closure_vars=caller_closure_vars,
                pipeline=pipeline,
                tilingkey_schema=tilingkey_schema,
                datatype_schema=datatype_schema,
                compile_timeout=compile_timeout,
                sanitizer=sanitizer,
            )
        else:
            # Legacy path: non-Tile function, wrap as pass-through
            @functools.wraps(f)
            def wrapper(*args, **kwargs_):
                return f(*args, **kwargs_)

            return wrapper

    if callable(target):
        return decorator(target)
    else:
        return decorator


def _is_tile_kernel(func) -> bool:
    """Detect if a function is a Tile-programming kernel based on its annotations.

    A Tile kernel has pl.Tensor, pl.Ptr, or DT_* scalar annotations
    on its parameters. These are created by pl.Tensor[[shape], dtype],
    pl.Ptr[dtype], or dtype (e.g. pl.DT_INT64) syntax.
    """
    hints = getattr(func, "__annotations__", {})
    if not hints:
        return False

    # Import type classes for isinstance check
    tensor_cls = None
    ptr_cls = None
    try:
        from pypto_pro.language.typing.tensor import Tensor

        tensor_cls = Tensor
    except ImportError:
        pass

    try:
        from pypto_pro.language.typing.ptr import Ptr

        ptr_cls = Ptr
    except ImportError:
        pass

    for key, val in hints.items():
        if key == "return":
            continue
        # pl.Tensor[[64, 128], pl.DT_FP16] returns a Tensor instance at runtime
        if tensor_cls is not None and (isinstance(val, tensor_cls) or val is tensor_cls):
            return True
        # pl.Ptr[pl.DT_FP16] returns a Ptr instance at runtime
        if ptr_cls is not None and (isinstance(val, ptr_cls) or val is ptr_cls):
            return True
        # DT_* values are DataType enum members at runtime.  String annotations
        # are retained when ``from __future__ import annotations`` is active.
        if isinstance(val, DataType) or (isinstance(val, str) and val.split(".")[-1].startswith("DT_")):
            return True
    return False


# Specialization identity for a kernel launched without tilingkey/datatype keys.
# (tilingkey_packed, dtype_consts, dtype_metadata, dtype_hash)
_NO_SPEC = (None, None, None, None)


class _TileJitKernel:
    """A JIT-compiled Tile kernel that supports bracket-launch syntax.

    Supports:
        kernel[stream, block_dim](x, y, z)  — explicit stream and block_dim
        kernel[block_dim](x, y, z)          — default stream, explicit block_dim
        kernel(x, y, z)                     — default stream, full core budget (auto)
    """

    def __init__(
        self,
        func,
        arch: str | None,
        auto_mutex=True,
        name=None,
        closure_vars=None,
        pipeline=None,
        tilingkey_schema=None,
        datatype_schema=None,
        compile_timeout=None,
        sanitizer=False,
    ):
        self._func = func
        self._arch = arch

        self._auto_mutex = auto_mutex
        self._name = name
        self._closure_vars = closure_vars
        self._pipeline = pipeline
        self._tilingkey_schema = tilingkey_schema
        self._datatype_schema = datatype_schema
        self._compile_timeout = compile_timeout
        self._sanitizer = sanitizer
        from pypto_pro.runtime.shape_policy import KernelSignatureSpec

        self._shape_signature_spec = KernelSignatureSpec.from_callable(func, closure_vars)
        self._compiled_by_signature: dict[tuple[tuple, str | None, int | None], "CompiledKernel"] = {}
        self._static_dim_slots_cache: tuple | None = None
        # Resolved bracket keys: sorted (tilingkey, datatype) items -> (tk snapshot,
        # dtype snapshot, specialization identity). Every call site in the tree writes
        # ``kernel[...](args)`` inline, so __getitem__ runs per launch and everything it
        # derives would otherwise be rederived per launch. Bounded by the number of
        # distinct specializations, which is the number of compiled variants; block_dim is
        # deliberately not part of the key, since nothing here depends on it and including
        # it would let a core-count sweep grow the memo without bound.
        self._bracket_memo: dict[tuple, tuple] = {}
        # Argument count for which _normalize_launch_args is a no-op: every parameter can
        # be filled positionally, so a full positional call already is the normalized
        # tuple. -1 when the signature rules that out (keyword-only, *args, **kwargs),
        # which never equals len(args) and therefore always takes the general path.
        signature = self._shape_signature_spec.python_signature
        positional = (inspect.Parameter.POSITIONAL_ONLY, inspect.Parameter.POSITIONAL_OR_KEYWORD)
        self._positional_arity = (
            len(signature.parameters)
            if signature is not None and all(p.kind in positional for p in signature.parameters.values())
            else -1
        )
        self.__name__ = func.__name__
        self.__doc__ = func.__doc__

    def __getitem__(self, key):
        """Support kernel[stream, block_dim], with optional tilingkey and datatype dicts.

        Returns a callable launcher that executes the compiled kernel.

        ``block_dim`` is the exact worker block count and must fit the current
        stream's torch_npu resource limits, including device defaults and
        npugraph_ex scopes; a request above the limit fails the launch instead
        of being silently reduced. Kernels must partition all work using
        ``get_block_num()`` (and ``get_subblock_num()`` for mixed vector
        workers), not a fixed host core count. A captured graph retains its
        launch dimensions until recaptured.

        For tilingkey kernels the third bracket element is the concrete key dict::

            kernel[stream, block_dim, {"NeedAttnMask": 1}](...)

        """
        stream, block_dim, tk_key, dtype_key = self._parse_launch_key(key)
        # block_dim is fixed by the bracket key, so validate it here instead of
        # re-checking the same value on every launch. It is kept out of the memo key
        # because nothing the memo holds depends on it.
        _validate_block_dim(block_dim)
        # get_stream_limit used to validate this on every invocation. Keep foreign
        # handles out of ACL, but validate the fixed explicit stream only once when
        # constructing the launcher. None resolves to a torch NPU stream at launch.
        if stream is not None and not isinstance(stream, torch.npu.Stream):
            raise InvalidType(f"stream must be torch.npu.Stream or None, got {type(stream).__name__}")
        try:
            memo_key = (
                None if tk_key is None else tuple(sorted(tk_key.items())),
                None if dtype_key is None else tuple(sorted(dtype_key.items())),
            )
            resolved = self._bracket_memo.get(memo_key)
        except (AttributeError, TypeError):
            # Not a dict at all, or a dict holding unhashable values. Fall through to the
            # validating branch, which rejects it with the schema's own message; a key that
            # cannot be looked up is also never stored.
            memo_key = None
            resolved = None
        if resolved is None:
            if self._tilingkey_schema is not None:
                self._tilingkey_schema.validate_concrete(tk_key)
            # Snapshot the specialization dicts. The identity below is resolved once from
            # them while codegen reads them again on a cache miss, so holding the caller's
            # objects would let a later mutation compile one variant under another's key --
            # poisoning the entry for every subsequent launch. Memoizing makes that sharper:
            # a poisoned entry would now outlive the bracket that created it. The memo key
            # is built from the dict's contents, so a mutated dict simply misses and
            # resolves afresh.
            tk_snapshot = None if tk_key is None else dict(tk_key)
            dtype_snapshot = None if dtype_key is None else dict(dtype_key)
            resolved = (tk_snapshot, dtype_snapshot, self._resolve_spec_identity(tk_snapshot, dtype_snapshot))
            if memo_key is not None:
                self._bracket_memo[memo_key] = resolved
        tk_snapshot, dtype_snapshot, spec = resolved
        arity = self._positional_arity

        def launcher(*args, **kwargs):
            self._validate_launch_arch()
            # A complete positional call is already normalized; skip the bind entirely.
            if kwargs or len(args) != arity:
                args = self._normalize_launch_args(args, kwargs)
            compiled = self._ensure_compiled(
                args, concrete_key=tk_snapshot, dtype_key=dtype_snapshot, spec=spec
            )
            _launch(compiled, args, block_dim, stream)

        return launcher

    def __call__(self, *args, **kwargs_):
        """Direct call: default stream, block_dim resolved to the stream's full budget."""
        if self._tilingkey_schema is not None or self._datatype_schema is not None:
            raise NotSupported(
                f"Kernel '{self.__name__}' has compile-time specialization and cannot be called directly; "
                "use bracket-launch syntax"
            )
        self._validate_launch_arch()
        if kwargs_ or len(args) != self._positional_arity:
            args = self._normalize_launch_args(args, kwargs_)
        compiled = self._ensure_compiled(args, spec=_NO_SPEC)
        _launch(compiled, args, _AUTO_BLOCK_DIM, None)

    def _validate_launch_arch(self) -> None:
        from pypto_pro.runtime.platform import get_platform_info

        platform_arch = get_platform_info().arch
        if self._arch is None:
            self._arch = platform_arch
        elif self._arch.strip().lower() != platform_arch:
            raise NotSupported(
                f"JIT arch {self._arch!r} does not match current platform arch {platform_arch!r}"
            )

    @property
    def arch(self):
        return self._arch

    @property
    def tilingkey_schema(self):
        return self._tilingkey_schema

    @property
    def datatype_schema(self):
        return self._datatype_schema

    def to_kernel_def(self, concrete_key: dict | None = None, datatype_consts: dict | None = None):
        """Create the KernelDef for one concrete tiling key and datatype specialization.

        ``concrete_key`` is the first positional argument for OPC compatibility.

        Shape binding is deliberately absent: the KernelDef carries the unbound function,
        and the bound signature reaches codegen through ``parse_target_program`` and
        ``probe_kernel_facts`` instead (see :func:`_codegen`).
        """
        # Create KernelDef directly with the closure captured by @pl.jit at
        # the user's decoration site.
        from pypto_pro.runtime.kernel import KernelDef, extract_func_source_info

        f = self._func
        (source_file, source_lines, source_lines_raw, line_offset, col_offset, func_def) = extract_func_source_info(f)

        return KernelDef(
            func=f,
            source_file=source_file,
            source_lines=source_lines,
            source_lines_raw=source_lines_raw,
            line_offset=line_offset,
            col_offset=col_offset,
            func_def=func_def,
            closure_vars=self._closure_vars or {},
            name=self._name,
            func_type=ir.FunctionType.Opaque,
            strict_ssa=False,
            meta_data=None,
            auto_mutex=self._auto_mutex,
            pipeline=self._pipeline,
            tilingkey_consts=concrete_key,
            datatype_consts=datatype_consts,
        )

    def _bind_runtime_args(self, args: tuple):
        """Validate tensor arguments and derive the static specialization signature."""
        bound_signature = self._shape_signature_spec.bind_runtime_args(args)
        python_args = self._shape_signature_spec.python_signature.bind(*args)
        for tensor_spec in self._shape_signature_spec.tensors:
            arg = python_args.arguments[tensor_spec.parameter_name]
            if arg is None:
                continue
            if not isinstance(arg, torch.Tensor):
                raise InvalidType(
                    f"Tensor parameter '{tensor_spec.parameter_name}' expected torch.Tensor, got {type(arg).__name__}"
                )
            expected_dtype = _pl_dtype_to_torch(tensor_spec.dtype)
            if expected_dtype is not None and arg.dtype != expected_dtype:
                raise InvalidType(
                    f"Tensor parameter '{tensor_spec.parameter_name}' dtype mismatch: "
                    f"expected {expected_dtype}, got {arg.dtype}"
                )
        return bound_signature

    def _bind_static_shapes(self, static_shapes):
        """Bind explicit binary-compilation shapes through the shared policy model."""
        return self._shape_signature_spec.bind_static_shapes(static_shapes)

    def _static_dim_slots(self):
        """Parameters carrying a StaticDim/StaticTail, i.e. the only ones whose runtime
        shape can contribute to ``static_signature``. Computed once; empty for a kernel
        declared entirely with ``pl.DYNAMIC`` and fixed dims, which lets _ensure_compiled
        skip binding the signature altogether."""
        slots = self._static_dim_slots_cache
        if slots is None:
            slots = self._static_dim_slots_cache = tuple(
                t.parameter_index for t in self._shape_signature_spec.tensors if t.requires_binding
            )
        return slots

    def _resolve_spec_identity(self, concrete_key, dtype_key):
        """Pack the specialization half of the cache key.

        Depends only on the bracket-launch key, never on the arguments, so callers that
        know it is fixed (``__getitem__``) resolve it once and pass it down.
        """
        tilingkey_packed = None
        if concrete_key is not None and self._tilingkey_schema is not None:
            tilingkey_packed = self._tilingkey_schema.pack(concrete_key)
        dtype_consts = _validate_datatype_key(self._datatype_schema, dtype_key)
        dtype_metadata = _datatype_metadata(self._datatype_schema, dtype_key, dtype_consts)
        return tilingkey_packed, dtype_consts, dtype_metadata, _datatype_hash(dtype_metadata)

    def _ensure_compiled(
        self, args: tuple, concrete_key: dict | None = None, dtype_key: dict | None = None,
        spec: tuple | None = None,
    ):
        """Return the compiled variant for one launch, compiling it on first use.

        This is the launch hot path: ``args`` is the runtime argument tuple in Python
        signature order. ``spec`` is the precomputed specialization identity from
        :meth:`_resolve_spec_identity`; ``__getitem__`` passes it because the bracket key
        pins it, so it is resolved here only when a caller did not.

        Ahead-of-time compilation without runtime arguments goes through
        :meth:`_compile_for_key` instead.
        """
        if spec is None:
            spec = self._resolve_spec_identity(concrete_key, dtype_key)
        tilingkey_packed, _, _, dtype_hash = spec

        # A cache hit needs only the key, so binding the full signature -- two
        # inspect.Signature.bind calls plus a BoundDimension per declared dimension -- is
        # deferred to the miss path, where codegen actually consumes it.
        if not self._static_dim_slots():
            # No parameter carries a StaticDim/StaticTail, so no dimension can ever be
            # marked static and the signature is provably empty for every launch.
            bound_signature = None
            static_signature = ()
        else:
            bound_signature = self._bind_runtime_args(args)
            static_signature = bound_signature.static_signature

        cached = self._compiled_by_signature.get((static_signature, dtype_hash, tilingkey_packed))
        if cached is not None:
            # No validation here: every caller launches immediately afterwards and the
            # launch path checks type, dtype, rank and every dimension. Doing it twice
            # per launch only duplicates the same TypeError.
            return cached

        if bound_signature is None:
            bound_signature = self._bind_runtime_args(args)
        return self._compile_variant(concrete_key, spec, bound_signature, static_signature)

    def _compile_for_key(self, concrete_key: dict | None = None, dtype_key: dict | None = None):
        """Compile one specialization ahead of any launch, without runtime arguments.

        Used by the PARALLEL_COMPILE conftest to warm the cache from a worker thread and by
        the tilingkey unit tests. Shapes come from the declared static policy
        (``_bind_static_shapes(None)``) since there are no tensors to read them from.
        """
        spec = self._resolve_spec_identity(concrete_key, dtype_key)
        tilingkey_packed, _, _, dtype_hash = spec
        bound_signature = self._bind_static_shapes(None)
        static_signature = bound_signature.static_signature
        cached = self._compiled_by_signature.get((static_signature, dtype_hash, tilingkey_packed))
        if cached is not None:
            return cached
        return self._compile_variant(concrete_key, spec, bound_signature, static_signature)

    def _compile_variant(self, concrete_key, spec, bound_signature, static_signature):
        """Codegen + build one variant and install it in the cache. Cache-miss path only.

        For tilingkey kernels, ``concrete_key`` selects the concrete field values baked into
        the IR; the packed 64-bit value keys the in-process cache and the per-key output subdir
        ``<build_dir>/tk_<packed>``. Codegen and compile are both per-key (the constants differ).
        """
        tilingkey_packed, dtype_consts, dtype_metadata, dtype_hash = spec
        self._arch = _setup_arch_env(self._arch)
        arch = self._arch
        logging.info(
            "Generating kernel '%s' for static shape signature %s",
            self.__name__,
            static_signature or "<dynamic-only>",
        )
        kernel_def = self.to_kernel_def(concrete_key, datatype_consts=dtype_consts)
        cg = _codegen(
            kernel_def,
            arch,
            clean_up=False,
            tilingkey_packed=tilingkey_packed,
            datatype_hash=dtype_hash,
            datatype_metadata=dtype_metadata,
            bound_signature=bound_signature,
            static_signature=static_signature,
            sanitizer=self._sanitizer,
        )
        if cg is None:
            raise RuntimeFailure(f"Failed to generate code for kernel '{self.__name__}'")

        # Resolve once for compiler flags, the native block-budget check and debug
        # recompilation. Every consumer must use this binary's same core geometry.
        target = get_jit_compile_config().resolve_kernel_target(
            arch, has_cube=cg.has_cube, has_vector=cg.has_vector,
        )
        compile_timeout = self._compile_timeout
        if compile_timeout is None:
            from pypto import pypto_impl
            compile_timeout = pypto_impl.CurrentScope().GetAllConfig().get("host.compile_timeout", 600)
        lib_path = _build_jit_so(
            cg,
            arch,
            clean_up=False,
            compile_timeout=compile_timeout,
            target=target,
        )
        if lib_path is None:
            raise RuntimeFailure(f"Failed to compile kernel '{self.__name__}'")

        # An aiv-only kernel emits vector code but no cube code; its block_dim
        # is bounded by the vector core count rather than the total core count.
        is_aiv_only = cg.has_vector and not cg.has_cube
        compiled = CompiledKernel(
            lib_path=lib_path, param_specs=cg.param_specs, is_aiv_only=is_aiv_only,
            kernel_name=cg.kernel_name, build_dir=cg.build_dir,
            has_cube=cg.has_cube, has_vector=cg.has_vector,
            target=target, source_file=cg.source_file,
            needs_print_debug=cg.needs_print_debug,
        )
        if self._sanitizer:
            # Pre-bind the sanitizer wrapper as the launch entry: it allocates
            # the GM log buffer, appends the hidden sanitizer_log arguments,
            # launches via the upstream entry, builds the single report file
            # and scans it for detections.
            compiled.entry = _build_sanitizer_entry(compiled, cg.build_dir)
        self._compiled_by_signature[(static_signature, dtype_hash, tilingkey_packed)] = compiled
        return compiled

    def _launch_key_error(self) -> str:
        if self._tilingkey_schema is not None and self._datatype_schema is not None:
            return "Expected kernel[stream, block_dim, tilingkey, datatype]"
        if self._tilingkey_schema is not None:
            return "Expected kernel[stream, block_dim, tilingkey]"
        if self._datatype_schema is not None:
            return "Expected kernel[stream, block_dim, datatype]"
        return "Expected kernel[stream, block_dim] or kernel[block_dim]"

    def _normalize_launch_args(self, args: tuple, kwargs: Mapping[str, object]) -> tuple:
        """Return launch arguments in Python signature order, including defaults."""
        bound = self._shape_signature_spec.python_signature.bind(*args, **dict(kwargs))
        bound.apply_defaults()
        return tuple(bound.arguments[name] for name in self._shape_signature_spec.python_signature.parameters)

    def _parse_launch_key(self, key):
        """Split the bracket key into (stream, block_dim, tilingkey_dict|None, dtype_dict|None).

        Checks the *shape* of the bracket -- which dicts must be present for this kernel's
        schemas -- but not the tilingkey field values. ``validate_concrete`` walks the
        schema and is left to ``__getitem__``'s memo-miss branch, since a key that has
        already been resolved once was already validated then, and an invalid key never
        reaches the memo.
        """
        tk_key = None
        dtype_key = None
        if isinstance(key, tuple):
            if len(key) == 4:
                stream, block_dim, tk_key, dtype_key = key
            elif len(key) == 3:
                stream, block_dim, third_key = key
                if self._tilingkey_schema is not None:
                    tk_key = third_key
                elif self._datatype_schema is not None:
                    dtype_key = third_key
                else:
                    tk_key = third_key
            elif len(key) == 2:
                stream, block_dim = key
            else:
                raise InvalidArgument(self._launch_key_error())
        else:
            stream = None
            block_dim = key

        if self._tilingkey_schema is not None:
            if tk_key is None:
                raise InvalidArgument(self._launch_key_error())
        elif tk_key is not None:
            raise InvalidArgument(self._launch_key_error())
        if self._datatype_schema is not None and dtype_key is None:
            raise InvalidArgument(self._launch_key_error())
        if self._datatype_schema is None and dtype_key is not None:
            raise InvalidArgument(self._launch_key_error())
        return stream, block_dim, tk_key, dtype_key
