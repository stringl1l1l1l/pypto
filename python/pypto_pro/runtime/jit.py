def _run_bisheng(
    bisheng_path: str,
    flags: list[str],
    arch: str,
    paths: CompilePaths,
    link_args: list[str],
    compile_timeout: int,
    output_path: str,
) -> bool:
    """Run bisheng to build the shared library at ``output_path``."""
    result = subprocess.run(
        [
            bisheng_path,
            *flags,
            *_build_llvm_args(arch),
            paths.final_kernel,
            *link_args,
            "-o",
            output_path,
        ],
        check=False,
        timeout=compile_timeout,
        capture_output=True,
    )
    if result.returncode == 0:
        return True
    logging.error("bisheng compilation failed with return code %s", result.returncode)
    logging.error("stdout: %s", result.stdout.decode())
    logging.error("stderr: %s", result.stderr.decode())
    return False


def _compile_shared_library(
    paths: CompilePaths,
    arch: str,
    generated: GeneratedKernel,
    clean_up: bool,
    compile_timeout: int,
) -> str | None:
    """Compile generated C++ and caller wrapper into a shared library.

    bisheng writes to a process-and-call-unique temp file in ``paths.build_dir`` rather
    than a shared fixed name: concurrent compiles of the same tilingkey target the same
    directory (e.g. distinct pytest-xdist workers compiling the same kernel/key), so a
    shared fixed output name would let one compile's rename race another's read. The temp
    file is renamed to call_kernel_<digest>.so, embedding a sha256 of the compiled bytes,
    and that hashed path is returned.
    """
    pto_lib_path = os.environ["ASCEND_TOOLKIT_HOME"]
    ascend_home_path = os.environ.get("ASCEND_HOME_PATH")
    if not ascend_home_path:
        raise RuntimeFailure("ASCEND_HOME_PATH is not set")
    link_args = _runtime_link_args(ascend_home_path)
    # The generated caller references the aclprof* tensor-info range interfaces
    # (aclprofStr2Id / aclprofRangePushEx / aclprofRangePop, declared in
    # acl/acl_prof.h); they are exported by libmsprofiler.so in the runtime lib
    # dir, so make sure it is on the link line.
    if "-lmsprofiler" not in link_args:
        link_args = link_args + ["-lmsprofiler"]

    resolved_enable_print_debug = generated.needs_print_debug
    flags = _build_bisheng_flags(
        pto_lib_path,
        arch,
        generated.target,
        generated.has_cross_sync,
        enable_print_debug=resolved_enable_print_debug,
    )
    flags.extend(_runtime_include_flags(ascend_home_path))
    bisheng_path = shutil.which("bisheng")
    if bisheng_path is None:
        logging.error("bisheng executable was not found")
        return None

    tmp_lib_path = os.path.join(paths.build_dir, f".call_kernel.{os.getpid()}.{uuid.uuid4().hex}.so")
    try:
        if not _run_bisheng(bisheng_path, flags, arch, paths, link_args, compile_timeout, tmp_lib_path):
            return None

        if clean_up:
            os.remove(paths.raw_cpp_path)
            os.remove(paths.final_kernel)

        lib_bytes = Path(tmp_lib_path).read_bytes()
        digest = hashlib.sha256(lib_bytes).hexdigest()[:12]
        unique_lib_path = os.path.join(paths.build_dir, f"call_kernel_{digest}.so")
        os.replace(tmp_lib_path, unique_lib_path)
        return unique_lib_path
    finally:
        if os.path.exists(tmp_lib_path):
            os.remove(tmp_lib_path)


def _codegen(
    prog,
    arch: str,
    clean_up: bool,
    tilingkey_packed: int | None = None,
    out_dir: str | None = None,
    datatype_hash: str | None = None,
    datatype_metadata: dict | None = None,
    *,
    bound_signature=None,
    static_signature: tuple[tuple[int, int, int], ...] = (),
    sanitizer: bool = False,
) -> CodegenResult | None:
    """Codegen: parse + generate the kernel source for one concrete tilingkey.

    Tilingkey field values are folded into the IR as constants, so each key produces a
    distinct kernel.cpp written into that key's output dir ``<build_dir>/tk_<packed>``.

    ``out_dir`` overrides that default location (see :func:`_prepare_codegen_inputs`) — pass a
    caller-unique dir when concurrent codegen would otherwise share the default path.
    """
    from pypto_pro.runtime.kernel import KernelDef

    if not isinstance(prog, KernelDef):
        raise CommonInner("CCE codegen requires a KernelDef with an explicit target section")

    source, out_dir = _prepare_codegen_inputs(
        prog, arch, tilingkey_packed, out_dir, datatype_hash, datatype_metadata,
        bound_signature=bound_signature, static_signature=static_signature)

    cube, vector = _parse_and_codegen_targets(
        source,
        arch,
        out_dir,
        bound_signature,
        sanitizer,
    )
    result = _assemble_cv_source(cube, vector)
    result.sanitizer = (cube is not None and cube.sanitizer) or (vector is not None and vector.sanitizer)
    result.source_file = getattr(source, "_source_file", "")

    result = _add_kernel_header(result)
    _write_codegen_artifacts(result)
    return result


def _build_jit_so(
    cg: CodegenResult,
    arch: str,
    clean_up: bool,
    compile_timeout: int,
    *,
    target: KernelTarget,
) -> str | None:
    """Write call_kernel.cpp next to the (already per-key) kernel.cpp in ``cg.build_dir`` and
    compile the .so. kernel.cpp, call_kernel.cpp and the resulting call_kernel_<digest>.so all
    share that one dir."""
    paths = _make_jit_paths(cg.build_dir)
    resolved_print_debug = cg.needs_print_debug

    # CCE: kernel.cpp holds only `<name>_impl`; define the __global__ entry that forwards to it.
    global_entry = ""
    if cg.needs_global_entry:
        global_entry = _make_global_entry(cg.kernel_name, cg.entry_params, target=target)

    caller_content = _generate_caller_cpp(
        kernel_params=cg.kernel_params,
        kernel_cpp_name="kernel.cpp",
        kernel_name=cg.kernel_name,
        has_cross_core_sync=cg.caller_cross_core_sync,
        enable_print_debug=resolved_print_debug,
        global_entry=global_entry,
        target=target,
        prof_param_specs=cg.param_specs,
        required_dynamic_ub_size=cg.required_dynamic_ub_size,
    )
    _atomic_write_text(Path(paths.final_kernel), caller_content)

    generated = GeneratedKernel(
        content=cg.content,
        has_cross_sync=cg.bisheng_cross_sync,
        needs_print_debug=cg.needs_print_debug,
        target=target,
    )
    return _compile_shared_library(paths, arch, generated, clean_up, compile_timeout)


