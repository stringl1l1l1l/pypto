def _static_signature_suffix(static_signature: tuple[tuple[int, int, int], ...]) -> str:
    if not static_signature:
        return ""
    digest = hashlib.sha256(repr(static_signature).encode("utf-8")).hexdigest()[:12]
    return f"__shape_{digest}"


def _prepare_codegen_inputs(
    kernel_def,
    arch: str,
    tilingkey_packed: int | None = None,
    out_dir: str | None = None,
    datatype_hash: str | None = None,
    datatype_metadata: dict | None = None,
    *,
    bound_signature=None,
    static_signature: tuple[tuple[int, int, int], ...] = (),
) -> tuple[object, str]:
    """Transform the KernelDef AST and create its per-tilingkey output directory.

    Tilingkey field values are baked into the IR as constants, so each concrete key produces
    its own ``kernel.cpp``. All keys of one kernel share the kernel build dir; this returns
    the KernelDef and the per-key subdir ``<build_dir>/tk_<packed>`` where that
    key's kernel.cpp, tiling headers, launcher and .so all live together.

    ``out_dir`` overrides the default ``<build_dir>/tk_<packed>`` location: callers that must
    keep concurrent codegen isolated (e.g. binary compile forks one process per dtype-combo, all
    sharing cwd) pass a caller-unique directory so distinct kernels never share a kernel.cpp.
    """
    artifact_prefix = _artifact_prefix_from_filename(
        getattr(kernel_def, "_source_file", None)
    )
    generated_source = None
    if kernel_def._pipeline is not None:
        from pypto_pro.runtime.pipeline import transform_pipeline
        from pypto_pro.runtime.pipeline._analyzer import probe_kernel_facts
        from pypto_pro.runtime.pipeline._dump import build_generated_file_source

        # Probe parse to learn which if-conditions are compile-time constants
        # (reuses the parser's own constant folding); drives dead-branch pruning.
        if_const_map, var_types = probe_kernel_facts(kernel_def, bound_signature)
        # The analysis below walks the kernel's AST from here, where the parser's
        # SpanTracker is not in scope. Publish one so its errors can point at the
        # code they are about instead of naming a line number in their text.
        from pypto_pro.language.parser._span_tracker import SpanTracker

        pipeline_spans = SpanTracker(
            kernel_def._source_file,
            kernel_def._source_lines,
            kernel_def._line_offset,
            kernel_def._col_offset,
        )
        with span_source(pipeline_spans.get_span):
            kernel_def._func_def = transform_pipeline(
                kernel_def._func_def,
                kernel_def._closure_vars,
                kernel_def._pipeline,
                if_const_map=if_const_map,
                var_types=var_types,
                tilingkey_consts=kernel_def._tilingkey_consts,
                datatype_consts=kernel_def._datatype_consts,
            )
        generated_source = build_generated_file_source(
            kernel_def._func_def,
            kernel_def._source_file,
            kernel_def._line_offset,
            kernel_def._col_offset,
            kernel_def._source_lines_raw,
        )
        kernel_def._pipeline = None

    if out_dir is None:
        build_dir = _make_artifact_build_dir(
            kernel_def, arch, test_prefix=artifact_prefix,
            tilingkey_suffix=_static_signature_suffix(static_signature))
        if datatype_hash is not None:
            build_dir = os.path.join(build_dir, f"dt_{datatype_hash}")
            write_datatype_metadata(build_dir, datatype_metadata)
        out_dir = _make_tilingkey_dir(build_dir, tilingkey_packed)
    Path(out_dir).mkdir(parents=True, exist_ok=True)
    # Dumped after out_dir exists so the transformed source lands next to the
    # kernel.cpp it produced, instead of in a cwd-relative ./build tree of its own.
    _dump_pipeline_generated_source(kernel_def, generated_source, out_dir)
    return kernel_def, out_dir


def _make_jit_paths(out_dir: str) -> CompilePaths:
    """JIT artifact paths within one tilingkey's output dir: kernel.cpp, call_kernel.cpp and
    the compiled library all live side by side in ``out_dir``. The compiled library is built
    under a process-unique temp name and renamed to call_kernel_<digest>.so
    (see :func:`_compile_shared_library`)."""
    return CompilePaths(
        build_dir=out_dir,
        raw_cpp_path=os.path.join(out_dir, "kernel.cpp"),
        final_kernel=os.path.join(out_dir, "call_kernel.cpp"),
    )


def _make_global_entry(
    kernel_name: str,
    entry_params: list[tuple[str, str, bool]],
    *,
    target: KernelTarget,
) -> str:
    """Decode eight-byte launch slots into the original ``<kernel_name>_impl`` types."""
    decls = []
    args = []
    for typ, name, is_ptr in entry_params:
        if is_ptr:
            decls.append(f"__gm__ {typ}* {name}")
            args.append(name)
        else:
            entry_type, _, decoded = _scalar_launch_abi(typ, name)
            decls.append(f"{entry_type} {name}")
            args.append(decoded)
    sig = ", ".join(decls)
    call_args = ", ".join(args)

    return (
        f"__global__ {target.entry_qualifier} void {kernel_name}({sig})\n"
        f"{{\n    {kernel_name}_impl({call_args});\n}}\n"
    )


def _codegen_target_cce(
    prog,
    arch: str,
    build_dir: str,
    target: ir.SectionKind,
    declared_directions: dict[int, TensorDirection] | None = None,
    required_dynamic_ub_size: int = 0,
) -> CodegenResult:
    """CCE codegen for one target-specific Program.

    Key-independent: produces no launcher and does not write final artifacts.
    """
    cce_codegen = CCECodegen(target)
    cpp_code = cce_codegen.generate_single(prog, arch)
    if "ffts_cross_core_sync" in cpp_code and arch == "a5":
        extra_headers = "#include <pto/npu/a5/custom/TSyncCVID.hpp>"
        guard = {
            ir.SectionKind.Cube: "#if defined(__DAV_CUBE__)",
            ir.SectionKind.Vector: "#if defined(__DAV_VEC__)",
        }[target]
        cpp_code = cpp_code.replace(guard, guard + "\n" + extra_headers, 1)
    tiling_headers = dict(cce_codegen.get_tiling_headers())

    # CCE emits the body as `__aicore__ inline void <name>_impl(...)`; derive the launcher ABI
    # from IR metadata instead of parsing generated C++ text, so C++ formatting/decorators can
    # change without breaking JIT launch parameter discovery.
    kernel_func = _get_kernel_ir_function(prog)
    kernel_name = kernel_func.name
    param_specs = _extract_param_specs(prog, declared_directions)
    entry_params = _entry_params_from_param_specs(param_specs)
    has_ffts = "set_ffts_base_addr" in cpp_code
    has_cross_sync = has_ffts or "set_intra_block" in cpp_code
    if has_ffts:
        entry_params.append(("int64_t", "ffts_addr", True))
    kernel_params = entry_params[:-1] if has_ffts else entry_params

    return CodegenResult(
        build_dir=build_dir,
        content=cpp_code,
        kernel_name=kernel_name,
        kernel_params=kernel_params,
        caller_cross_core_sync=has_ffts,
        bisheng_cross_sync=has_cross_sync,
        needs_print_debug=_detect_print_debug_from_cpp(cpp_code),
        param_specs=param_specs,
        needs_global_entry=True,
        entry_params=entry_params,
        tiling_headers=tiling_headers,
        has_cube=target == ir.SectionKind.Cube,
        has_vector=target == ir.SectionKind.Vector,
        required_dynamic_ub_size=required_dynamic_ub_size,
    )


def _entry_param_declarations(entry_params: list[tuple[str, str, bool]]) -> str:
    return ", ".join(
        f"__gm__ {typ}* {name}" if is_ptr else f"{typ} {name}"
        for typ, name, is_ptr in entry_params
    )


def _target_call_args(result: CodegenResult) -> str:
    return ", ".join(name for _, name, _ in result.entry_params)


def _assemble_cv_source(
    cube: CodegenResult | None,
    vector: CodegenResult | None,
) -> CodegenResult:
    """Assemble independently generated target sources behind one impl entry."""
    results = [result for result in (cube, vector) if result is not None]
    if not results:
        raise CommonInner("Cannot assemble Cube/Vector source without a target")

    reference = results[0]
    for result in results[1:]:
        if result.kernel_name != reference.kernel_name:
            raise CommonInner("Cube/Vector kernel names do not match")
        if result.param_specs != reference.param_specs:
            raise CommonInner("Cube/Vector kernel parameter specifications do not match")
        if result.kernel_params != reference.kernel_params:
            raise CommonInner("Cube/Vector kernel ABIs do not match")
        if result.build_dir != reference.build_dir:
            raise CommonInner("Cube/Vector build directories do not match")
        if result.tiling_headers != reference.tiling_headers:
            raise CommonInner("Cube and Vector tiling headers must be identical")

    needs_ffts = any(result.caller_cross_core_sync for result in results)
    entry_params = list(reference.kernel_params)
    if needs_ffts:
        entry_params.append(("int64_t", "ffts_addr", True))

    wrapper_lines = [
        "",
        f"__aicore__ inline void {reference.kernel_name}_impl("
        f"{_entry_param_declarations(entry_params)})",
        "{",
    ]
    if cube is not None:
        wrapper_lines.extend(
            [
                "#if defined(__DAV_CUBE__)",
                f"    {reference.kernel_name}_impl_cube({_target_call_args(cube)});",
                "#endif",
            ]
        )
    if vector is not None:
        wrapper_lines.extend(
            [
                "#if defined(__DAV_VEC__)",
                f"    {reference.kernel_name}_impl_vector({_target_call_args(vector)});",
                "#endif",
            ]
        )
    wrapper_lines.extend(["}", ""])

    return CodegenResult(
        build_dir=reference.build_dir,
        content="\n".join([*(result.content for result in results), *wrapper_lines]),
        kernel_name=reference.kernel_name,
        kernel_params=list(reference.kernel_params),
        caller_cross_core_sync=needs_ffts,
        bisheng_cross_sync=any(result.bisheng_cross_sync for result in results),
        needs_print_debug=any(result.needs_print_debug for result in results),
        param_specs=list(reference.param_specs),
        needs_global_entry=True,
        entry_params=entry_params,
        tiling_headers=dict(reference.tiling_headers),
        has_cube=cube is not None,
        has_vector=vector is not None,
        required_dynamic_ub_size=max(result.required_dynamic_ub_size for result in results),
    )


def _parse_and_codegen_targets(
    kernel_def,
    arch: str,
    build_dir: str,
    bound_signature=None,
    sanitizer: bool = False,
) -> tuple[CodegenResult | None, CodegenResult | None]:
    """Parse both targets, treating a sectionless kernel as shared by both.

    With ``sanitizer`` enabled, each parsed target program is instrumented
    (block.sanitizer_log records injected, one per detection type and
    sanitizer_log pointer + capacity scalar appended to the kernel signature);
    the flag is carried on the returned CodegenResults."""
    programs = {}
    matched = {}
    requires_simt = False
    max_vec_tile_end = 0
    for target in (ir.SectionKind.Cube, ir.SectionKind.Vector):
        programs[target], matched[target] = kernel_def.parse_target_program(
            target=target,
            bound_signature=bound_signature,
        )
        requires_simt = requires_simt or kernel_def.requires_simt
        max_vec_tile_end = max(max_vec_tile_end, kernel_def.max_vec_tile_end)
    # Tensor directions are keyed by stable source parameter index; unspecified
    # tensor parameters default to TensorDirection.INPUT.
    declared_directions = kernel_def.last_param_directions

    if not any(matched.values()):
        matched = {
            ir.SectionKind.Cube: True,
            ir.SectionKind.Vector: True,
        }

    required_dynamic_ub_size = _infer_dynamic_ub_size(requires_simt, max_vec_tile_end)

    if sanitizer:
        from pypto.pypto_impl.ir import Pass as IRPass

        sanitizer_pass = IRPass.sanitizer()
        target_list = [t for t in (ir.SectionKind.Cube, ir.SectionKind.Vector)
                       if matched.get(t) and programs.get(t) is not None]
        for target in target_list:
            programs[target] = sanitizer_pass(programs[target])

    results = {
        target: (
            _codegen_target_cce(
                programs.get(target), arch, build_dir, target=target,
                declared_directions=declared_directions,
                required_dynamic_ub_size=required_dynamic_ub_size,
            )
            if matched.get(target)
            else None
        )
        for target in (ir.SectionKind.Cube, ir.SectionKind.Vector)
    }
    for target in (ir.SectionKind.Cube, ir.SectionKind.Vector):
        if results[target] is not None:
            results[target].sanitizer = sanitizer
    return results[ir.SectionKind.Cube], results[ir.SectionKind.Vector]


def _write_codegen_artifacts(result: CodegenResult) -> None:
    """Write the final assembled source and shared tiling headers once."""
    Path(result.build_dir).mkdir(parents=True, exist_ok=True)
    _atomic_write_text(Path(result.build_dir, "kernel.cpp"), result.content)
    for header_name, header_content in result.tiling_headers.items():
        _atomic_write_text(Path(result.build_dir, header_name), header_content)


def _add_kernel_header(result: CodegenResult) -> CodegenResult:
    """Add the translation-unit header after all target sources are assembled."""
    header = KERNEL_HEADER_SINGLE
    if result.needs_print_debug:
        header += "\n#define __ENABLE_ASC_PRINTF__ 1\n"
    return dataclasses.replace(
        result,
        content=f"{header}\n{result.content.lstrip()}",
    )


def _dump_pipeline_generated_source(
    kernel_def,
    source: str | None,
    out_dir: str,
) -> None:
    """Preserve the transformed-pipeline debug artifact next to this key's kernel.cpp.

    ``out_dir`` is already unique per tilingkey/dtype (``tk_<packed>`` for JIT, a
    caller-supplied per-key dir for binary compile), so the dump lands beside the
    kernel.cpp it produced and needs no variant suffix to stay distinct.
    """
    if not source:
        return
    _atomic_write_text(Path(out_dir, "pipeline_generated.py"), source)


