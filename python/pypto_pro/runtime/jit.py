def _sanitize_artifact_component(value: str) -> str:
    cleaned = re.sub(r"[^0-9A-Za-z_.-]+", "_", value).strip("._")
    return cleaned or "kernel"


def _artifact_prefix_from_frame(frame) -> str | None:
    """Infer a readable artifact prefix from a Python frame."""
    filename = frame.f_code.co_filename
    return _artifact_prefix_from_filename(filename)


def _artifact_prefix_from_filename(filename: str | None) -> str | None:
    """Infer a readable artifact prefix from a Python source filename."""
    if not filename:
        return None
    stem = Path(filename).stem
    if not stem.startswith("test_"):
        return None
    suffix = stem[len("test_"):]
    return _sanitize_artifact_component(suffix or stem)


def _infer_test_artifact_prefix() -> str | None:
    frame = inspect.currentframe()
    try:
        frame = frame.f_back
        while frame is not None:
            prefix = _artifact_prefix_from_frame(frame)
            if prefix is not None:
                return prefix
            frame = frame.f_back
    finally:
        del frame
    return None


def _current_device_id() -> str | None:
    """The NPU device id this process is bound to, or None if the NPU is not initialized."""
    try:
        if not torch.npu.is_initialized():
            return None
        return str(torch.npu.current_device())
    except Exception:
        return None


def _current_rank() -> str | None:
    """This process's rank in its process group, or None outside a distributed job."""
    try:
        dist = torch.distributed
        if dist.is_available() and dist.is_initialized():
            return str(dist.get_rank())
    except Exception:
        return None
    return None


def _process_identity_tag() -> str:
    """The build dir name segment identifying this process: ``__d<device>_r<rank>``.

    Either component is omitted when unavailable (``__d0`` outside a distributed job); with
    both unavailable the tag is empty.
    """
    parts = []
    device = _current_device_id()
    if device:
        parts.append(f"d{device}")
    rank = _current_rank()
    if rank:
        parts.append(f"r{rank}")
    return f"__{'_'.join(parts)}" if parts else ""


def _make_artifact_build_dir(prog, arch: str, test_prefix: str | None = None, tilingkey_suffix: str = "") -> str:
    """The per-kernel build dir. All tilingkeys of one kernel share this dir; each concrete
    key gets a ``tk_<packed>`` subdir under it (see :func:`_make_tilingkey_dir`)."""
    prog_name = getattr(prog, "name", None) or getattr(prog, "_name", None)
    prog_name = prog_name or getattr(prog, "func_name", None) or "kernel"
    safe_name = _sanitize_artifact_component(str(prog_name))
    test_prefix = test_prefix if test_prefix is not None else _infer_test_artifact_prefix()
    readable_prefix = f"{test_prefix}__{safe_name}" if test_prefix and test_prefix != safe_name else safe_name
    work_path = os.environ.get("ASCEND_WORK_PATH", "").strip()
    root = os.path.join(os.path.expanduser(work_path), "PYPTO_PRO") if work_path else "."
    return os.path.join(
        root,
        "build",
        f"{readable_prefix}__{arch}{tilingkey_suffix}{_process_identity_tag()}")


def _make_tilingkey_dir(build_dir: str, tilingkey_packed: int | None) -> str:
    """The per-tilingkey subdir under the kernel build dir. Holds this key's kernel.cpp,
    tiling headers, call_kernel.cpp and the compiled call_kernel_<digest>.so (bisheng
    writes to a per-call temp file, which is then renamed to embed a content hash). Keys
    without a tiling_key use ``tk_none`` so the layout is uniform."""
    suffix = "none" if tilingkey_packed is None else format(tilingkey_packed, "x")
    return os.path.join(build_dir, f"tk_{suffix}")


def _dtype_record(dtype: DataType) -> dict:
    return {"name": str(dtype)}


def _validate_datatype_schema(datatype) -> dict[str, str] | None:
    """Validate the decorator's datatype mapping without function-specific checks."""
    if datatype is None:
        return None
    if not isinstance(datatype, dict) or not datatype:
        raise InvalidType("datatype must be a non-empty dict mapping param name to dtype variable name")

    for param_name, var_name in datatype.items():
        if not isinstance(param_name, str) or not param_name:
            raise InvalidArgument(f"datatype param names must be non-empty strings, got {param_name!r}")
        if not isinstance(var_name, str) or not var_name.isidentifier():
            raise InvalidType(
                f"datatype variable for param '{param_name}' must be a valid Python identifier, got {var_name!r}"
            )
    return datatype


def _validate_datatype_schema_context(spec: dict[str, str] | None, func, tilingkey_schema) -> None:
    if spec is None:
        return
    param_names = set(inspect.signature(func).parameters)
    missing = sorted(set(spec) - param_names)
    if missing:
        raise InvalidArgument(f"datatype params {missing} do not match kernel function '{func.__name__}' parameters")
    var_names = set(spec.values())
    param_conflicts = sorted(var_names & param_names)
    if param_conflicts:
        raise InvalidOperation(f"datatype variable names conflict with kernel params: {param_conflicts}")
    if tilingkey_schema is not None:
        tk_conflicts = sorted(var_names & set(tilingkey_schema.field_names()))
        if tk_conflicts:
            raise InvalidOperation(f"datatype variable names conflict with tiling_key fields: {tk_conflicts}")


def _validate_datatype_key(spec: dict[str, str] | None, dtype_key: dict | None) -> dict[str, DataType] | None:
    """Validate one launch-time dtype dict and return var_name -> DataType constants."""
    if spec is None:
        if dtype_key is not None:
            raise InvalidArgument("datatype dict was provided but this kernel has no datatype schema")
        return None
    if not isinstance(dtype_key, dict):
        raise InvalidType("datatype kernel launch requires a dtype dict")

    expected = set(spec)
    actual = set(dtype_key)
    if actual != expected:
        raise InvalidArgument(f"datatype keys {sorted(actual)} do not match schema params {sorted(expected)}")

    var_to_dtype: dict[str, DataType] = {}
    for param_name, var_name in spec.items():
        dtype = dtype_key[param_name]
        if not isinstance(dtype, DataType):
            raise InvalidType(f"datatype['{param_name}'] must be a pypto_pro.DataType, got {type(dtype).__name__}")
        existing = var_to_dtype.get(var_name)
        if existing is not None and existing != dtype:
            raise InvalidType(f"datatype params mapped to variable '{var_name}' disagree: {existing} vs {dtype}")
        var_to_dtype[var_name] = dtype
    return var_to_dtype


def _datatype_metadata(
    spec: dict[str, str] | None,
    dtype_key: dict[str, DataType] | None,
    dtype_consts: dict[str, DataType] | None,
) -> dict | None:
    if spec is None:
        return None
    dtype_key = dtype_key or {}
    dtype_consts = dtype_consts or {}
    return {
        "params": {
            param_name: {
                "variable": var_name,
                "dtype": _dtype_record(dtype_key[param_name]),
            }
            for param_name, var_name in sorted(spec.items())
        },
        "constants": {var_name: _dtype_record(dtype) for var_name, dtype in sorted(dtype_consts.items())},
    }


def _datatype_hash(metadata: dict | None) -> str | None:
    if metadata is None:
        return None
    payload = json.dumps(metadata, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def _atomic_write_text(path: Path, content: str) -> None:
    """Write ``content`` to ``path`` so concurrent readers never see a partial file.

    Unlike ``Path.write_text``, which truncates the target to zero bytes before writing, this
    writes a sibling temp file and renames it over the target: a reader gets either the complete
    old content or the complete new content. Readers holding an open descriptor keep reading the
    old content until they close it.

    The temp file is a sibling because rename is only atomic within one filesystem, is named
    with pid and a uuid so two writers never share it, and carries a leading dot to stay out of
    the ``*.h`` directory scans in pypto_compile.
    """
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{uuid.uuid4().hex}.tmp")
    try:
        tmp.write_text(content, encoding="utf-8")
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink()


def write_datatype_metadata(output_dir: str, metadata: dict | None) -> None:
    """Write datatype.json into an artifact directory when dtype specialization is active."""
    if metadata is None:
        return
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    _atomic_write_text(
        Path(output_dir, "datatype.json"),
        json.dumps(metadata, indent=2, sort_keys=True) + "\n",
    )


def _pack_factor(dtype: DataType | None) -> int:
    """How many elements of ``dtype`` torch reports as one storage unit along the packed axis.

    A sub-byte dtype has no torch dtype of its own, so callers pass the packed storage buffer
    (uint8, two fp4 per byte) and torch reports its shape in those storage units. pypto counts
    elements everywhere, so the packed axis -- the innermost one, the only axis a sub-byte
    element can be packed along -- has to be scaled back up before a tensor argument is
    compared against its ParamSpec or fed to the dynamic ABI tail. Whole-byte dtypes are
    already 1:1, and note that ``8 // 32`` is 0, not 1, so a wide dtype needs the clamp too.

    This depends only on the dtype, so the launch plan resolves it once per compiled kernel
    and the launch path just multiplies (see :class:`_LaunchPlan`).
    """
    if dtype is None:
        return 1
    return max(8 // dtype.get_bit(), 1)


def _pl_dtype_to_torch(dtype: DataType):
    """Return the torch.dtype an argument for this pl DataType must have, or None if unknown."""
    return _PL_DTYPE_TO_TORCH.get(str(dtype))


def _get_kernel_ir_function(prog):
    """Return the Opaque IR function that serves as the kernel entry."""
    from pypto.pypto_impl.ir import FunctionType

    for f in prog.functions.values():
        if f.func_type == FunctionType.Opaque:
            return f
    raise CommonInner(
        f"No Opaque kernel entry function found in program '{prog.name}' "
        f"(functions: {list(prog.functions)})"
    )


def _align_up(value: int, alignment: int) -> int:
    return (value + alignment - 1) // alignment * alignment


def _infer_dynamic_ub_size(requires_simt: bool, tile_high_water: int) -> int:
    """Infer A5 launch dynamic UB from parser-collected mixed-kernel facts."""
    if not requires_simt:
        return 0
    required = _align_up(max(0, tile_high_water - _A5_STATIC_UB_SIZE), _A5_UB_ALIGNMENT)
    if _A5_STATIC_UB_SIZE + required > _A5_MAX_USER_UB_SIZE:
        raise OutOfRange(
            f"SIMT kernel Vec Tile high-water mark {tile_high_water} bytes requires "
            f"static_ub_size={_A5_STATIC_UB_SIZE} and dynamic_ub_size={required}, but A5 allows at most "
            f"{_A5_MAX_USER_UB_SIZE} bytes of combined static and dynamic UB "
            f"(dynamic UB limit {_A5_MAX_DYNAMIC_UB_SIZE} bytes)"
        )
    return required


def _extract_param_specs(
    prog,
    declared_directions: dict[int, TensorDirection] | None = None,
) -> list[ParamSpec]:
    """Extract parameter descriptions from the kernel function in an ir.Program.

    Tensor directions are keyed by parameter index because codegen may rename
    parameters while preserving their order. Unspecified tensors default to
    TensorDirection.INPUT.
    """
    func = _get_kernel_ir_function(prog)
    declared_directions = declared_directions or {}
    specs: list[ParamSpec] = []
    for parameter_index, var in enumerate(func.params):
        t = var.type
        if isinstance(t, TensorType):
            shape = [s.value if isinstance(s, ConstInt) else (s.name if isinstance(s, Var) else -1) for s in t.shape]
            direction = declared_directions.get(parameter_index, TensorDirection.INPUT)
            specs.append(ParamSpec(var.name, ParamKind.TENSOR, t.dtype, shape, direction))
        elif isinstance(t, PtrType):
            specs.append(ParamSpec(var.name, ParamKind.PTR, t.dtype, None))
        elif isinstance(t, TupleType):
            # Tiling struct param: passed as a single uint8 device buffer pointer.
            specs.append(ParamSpec(var.name, ParamKind.TILING, None, None))
        elif isinstance(t, ScalarType):
            specs.append(ParamSpec(var.name, ParamKind.SCALAR, t.dtype, None))
    return specs


def _cce_cpp_type_from_dtype(dtype: DataType | None, *, param_name: str) -> str:
    """Return the CCE C++ scalar/element type string for a DataType."""
    if dtype is None:
        raise InvalidType(f"Parameter '{param_name}' has no dtype")
    cpp_type = dtype.to_c_type_string()
    if not cpp_type or cpp_type == "unknown":
        raise InvalidType(f"Unsupported CCE ABI dtype {dtype} for parameter '{param_name}'")
    return cpp_type


def _entry_params_from_param_specs(param_specs: list[ParamSpec]) -> list[tuple[str, str, bool]]:
    """Build launcher entry params from IR metadata instead of parsing generated C++."""
    params: list[tuple[str, str, bool]] = []
    for spec in param_specs:
        if spec.kind in (ParamKind.TENSOR, ParamKind.PTR):
            params.append((_cce_cpp_type_from_dtype(spec.dtype, param_name=spec.name), spec.name, True))
        elif spec.kind == ParamKind.TILING:
            params.append(("uint8_t", spec.name, True))
        elif spec.kind == ParamKind.SCALAR:
            params.append((_cce_cpp_type_from_dtype(spec.dtype, param_name=spec.name), spec.name, False))

    params.extend(("int64_t", dim_name, False) for dim_name in _collect_dyn_vars(param_specs))
    return params


def _iter_tensor_dynamic_dims(spec: ParamSpec):
    """Yield dynamic dimension symbols from a tensor param spec."""
    if spec.kind != ParamKind.TENSOR or spec.shape is None:
        return
    for dim in spec.shape:
        if isinstance(dim, str):
            yield dim


def _collect_dyn_vars(param_specs: list[ParamSpec]) -> list[str]:
    """Return dynamic shape variable names in first-occurrence order (mirrors ptoas codegen)."""
    seen: set[str] = set()
    result: list[str] = []
    for spec in param_specs:
        for dim in _iter_tensor_dynamic_dims(spec):
            if dim not in seen:
                result.append(dim)
                seen.add(dim)
    return result


def _validate_scalar_arg(i: int, arg, spec: ParamSpec) -> None:
    """Validate one scalar arg against its ParamSpec."""
    if not isinstance(arg, (int, float, bool)):
        raise InvalidType(f"arg[{i}] '{spec.name}': expected Python scalar (int/float/bool), got {type(arg).__name__}")
    # bool is a subclass of int: valid for BOOL and integer dtypes only.
    if isinstance(arg, bool):
        if not (spec.dtype == DataType.BOOL or spec.dtype.is_signed_int() or spec.dtype.is_unsigned_int()):
            raise InvalidType(
                f"arg[{i}] '{spec.name}': bool value passed for non-boolean/non-integer dtype {spec.dtype}"
            )
    elif isinstance(arg, float) and not spec.dtype.is_float():
        raise InvalidType(f"arg[{i}] '{spec.name}': float value passed for non-float dtype {spec.dtype}")
    elif isinstance(arg, int) and not spec.dtype.is_signed_int() and not spec.dtype.is_unsigned_int():
        raise InvalidType(f"arg[{i}] '{spec.name}': int value passed for non-integer dtype {spec.dtype}")


def _pack_tiling_arg(args: tuple) -> tuple:
    """If the last arg is a tiling class instance, replace it with a device buffer tensor.

    The tiling instance is serialized to its C-struct byte layout, wrapped in a uint8
    CPU tensor, and moved to the same device as the other tensor args. The kernel
    receives a single ``uint8_t*`` pointer and copies the struct in at its entry.

    The returned tuple holds the device tensor as its last element, which keeps it alive
    through the launch (the caller's ``args`` stays referenced until ``call_kernel``).

    Args:
        args: Runtime arguments tuple passed to launch.

    Returns:
        args with the tiling instance replaced by the device tensor (unchanged if no
        tiling instance is present).
    """
    from pypto_pro.language.typing._tiling import is_tiling_class, tiling_instance_to_bytes

    if not args:
        return args
    last_arg = args[-1]
    if not is_tiling_class(type(last_arg)):
        return args

    buf = tiling_instance_to_bytes(last_arg)
    # Pick the device from an existing tensor arg (inputs/outputs are already on device).
    device = None
    for a in args[:-1]:
        dev = getattr(a, "device", None)
        if dev is not None:
            device = dev
            break
    cpu_t = torch.frombuffer(bytearray(buf), dtype=torch.uint8)
    tiling_t = cpu_t.to(device) if device is not None else cpu_t
    return args[:-1] + (tiling_t,)


class _LaunchPlan:
    """Everything about a launch that depends only on the kernel's ParamSpecs.

    Which parameter is a tensor, what torch dtype it must carry, which dimensions are
    compile-time constants, which are dynamic ABI variables, and the order those variables
    are appended in: none of that can change once the kernel is compiled, so it is resolved
    here exactly once and the hot path just walks flat tuples.

    Attributes:
        n_params: Expected argument count.
        has_tiling: Whether any parameter is a tiling struct (skips _pack_tiling_arg).
        slots: Per-parameter descriptors in ABI order. Tensor slots are
            ``(True, index, name, torch_dtype | None, rank, const_dims, dyn_dims, pack)``
            where ``rank`` is -1 for parameters whose shape is not checked (PTR, or no
            declared shape), ``dyn_dims`` lists the dimensions this parameter contributes
            to the dynamic ABI tail, and ``pack`` is the sub-byte packing factor from
            :func:`_pack_factor` (1 for every whole-byte dtype). Scalar slots are
            ``(False, index, spec, ctype)``.
        dyn_checks: ``(name, ((param_index, dim_index, pack_mult), ...))`` for dynamic
            variables that appear more than once and therefore must agree across
            arguments. ``pack_mult`` is the slot's ``pack`` on the packed axis and 1
            everywhere else, so the comparison is made in elements.
        dyn_count: Total length of the dynamic ABI tail.

    Walking the slots in order and emitting each slot's ``dyn_dims`` reproduces the
    first-occurrence ordering the ABI expects, which lets the launch path read each
    tensor's ``.shape`` once instead of rebuilding the torch.Size per dynamic dimension.
    """

    __slots__ = ("n_params", "has_tiling", "slots", "dyn_checks", "dyn_count")

    def __init__(self, param_specs: list[ParamSpec]) -> None:
        self.n_params = len(param_specs)
        self.has_tiling = any(spec.kind == ParamKind.TILING for spec in param_specs)
        slots: list[tuple] = []
        occurrences: dict[str, list[tuple[int, int, int]]] = {}
        sources: dict[str, tuple[int, int]] = {}
        for index, spec in enumerate(param_specs):
            if spec.kind not in (ParamKind.TENSOR, ParamKind.PTR, ParamKind.TILING):
                ctype = _PL_DTYPE_TO_CTYPE.get(str(spec.dtype))
                if ctype is None:
                    # A property of the dtype, not of any argument: reject it once here
                    # rather than on every launch.
                    raise InvalidType(
                        f"No ctypes mapping for scalar dtype {spec.dtype} "
                        f"(param '{spec.name}'). FP16/BF16 scalars are not supported."
                    )
                slots.append((False, index, spec, ctype))
                continue
            # PTR params and shapeless specs stay unchecked.
            checked = spec.kind != ParamKind.PTR and spec.shape is not None
            rank = -1
            consts: tuple = ()
            # A sub-byte dtype arrives packed into uint8 storage; spec.shape counts
            # elements, so the innermost axis is scaled by `pack` before any comparison.
            pack = _pack_factor(spec.dtype) if checked else 1
            if checked:
                rank = len(spec.shape)
                consts = tuple(
                    (d, v) for d, v in enumerate(spec.shape) if isinstance(v, int) and v != -1
                )
                for dim, value in enumerate(spec.shape):
                    if isinstance(value, str):
                        occurrences.setdefault(value, []).append(
                            (index, dim, pack if dim == rank - 1 else 1)
                        )
            # Only TENSOR params feed the dynamic ABI tail.
            own_dyn: list[int] = []
            if spec.kind == ParamKind.TENSOR and spec.shape is not None:
                for dim, value in enumerate(spec.shape):
                    if isinstance(value, str) and value not in sources:
                        sources[value] = (index, dim)
                        own_dyn.append(dim)
            dtype = _pl_dtype_to_torch(spec.dtype) if checked else None
            slots.append((True, index, spec.name, dtype, rank, consts, tuple(own_dyn), pack))
        self.slots = tuple(slots)
        # A name seen once can never disagree with itself; only repeats need checking.
        self.dyn_checks = tuple(
            (name, tuple(where)) for name, where in occurrences.items() if len(where) > 1
        )
        self.dyn_count = len(sources)
        # The generated call_kernel signature declares its dynamic dimensions in the order
        # _collect_dyn_vars produces (via _entry_params_from_param_specs); `sources` above
        # rederives that order to build the matching argument tail. Two independent
        # derivations of one ABI ordering do not fail loudly when they drift -- the
        # arguments simply land in the wrong slots and the kernel reads the wrong extents
        # off device memory. Tie them together here: once per compiled kernel, never on the
        # launch path.
        codegen_order = tuple(_collect_dyn_vars(param_specs))
        if tuple(sources) != codegen_order:
            raise CommonInner(
                "dynamic ABI tail disagrees with the generated kernel signature: "
                f"launch order {tuple(sources)}, codegen order {codegen_order}"
            )


def _build_launch_entry(compiled: "CompiledKernel"):
    """Bind one compiled kernel to a closure that launches it with no per-call setup.

    The shared library, its ``call_kernel`` entry point and the static launch plan are
    resolved once here; the returned closure only touches the arguments themselves.

    ``call_kernel.argtypes`` is declared from the plan so the hot path can hand ctypes
    plain Python ints and let it convert them at the call boundary in C, instead of
    allocating one ctypes object per argument on every launch. The types mirror the
    generated ``extern "C"`` signature exactly (see :func:`_generate_caller_cpp` and
    :func:`_entry_params_from_param_specs`): ``uint32_t blockDim``, ``void* stream``,
    one ``uint8_t*`` per tensor/ptr/tiling parameter, the scalar's own C type, then one
    ``int64_t`` per dynamic dimension. Each compiled kernel owns its CDLL handle, so the
    declaration cannot leak between kernels.
    """
    plan = _LaunchPlan(compiled.param_specs)
    lib = ctypes.CDLL(compiled.lib_path)
    call_kernel = lib.call_kernel
    n_params = plan.n_params
    has_tiling = plan.has_tiling
    slots = plan.slots
    dyn_checks = plan.dyn_checks
    # Scalars carry their own ctype; everything else crosses as an opaque pointer.
    # Dynamic dimensions use int64_t in both the generated entry and the IR.
    call_kernel.argtypes = (
        [ctypes.c_uint32, ctypes.c_void_p]
        + [ctypes.c_void_p if slot[0] else slot[3] for slot in slots]
        + [ctypes.c_int64] * plan.dyn_count
    )
    # Positive results are the actual block count; negative results carry native
    # resource-query errors. int64_t preserves the error tag above its 32-bit detail.
    call_kernel.restype = ctypes.c_int64
    logger = logging.getLogger()
    # Exception-dump bookkeeping. The addresses and shapes it caches are per-launch, so
    # the call itself has to stay on the hot path -- but the import and the kernel's own
    # identity do not, and _load_lib used to redo both on every launch.
    from pypto_pro.runtime.exception_dump import set_dump_info as _set_dump_info

    def entry(args: tuple, block_dim: int, stream):
        if has_tiling:
            args = _pack_tiling_arg(args)
        if len(args) != n_params:
            raise InvalidType(f"Expected {n_params} args, got {len(args)}")

        # Plain Python values in ABI order; argtypes converts them at the call.
        abi_args = []
        append = abi_args.append
        dyn_values: list = []
        for slot in slots:
            index = slot[1]
            arg = args[index]
            if not slot[0]:
                _validate_scalar_arg(index, arg, slot[2])
                append(arg)
                continue
            _, _, name, expected_dtype, rank, consts, dyn_dims, pack = slot
            if arg is None:
                append(None)  # ctypes maps None to a null void*
                if dyn_dims:
                    dyn_values.extend([0] * len(dyn_dims))
                continue
            if not isinstance(arg, torch.Tensor):
                raise InvalidType(f"arg[{index}] '{name}': expected torch.Tensor, got {type(arg).__name__}")
            if rank >= 0:
                # torch.dtype values are singletons, so identity is enough and cheaper.
                if expected_dtype is not None and arg.dtype is not expected_dtype:
                    raise InvalidType(
                        f"arg[{index}] '{name}': dtype mismatch — expected {expected_dtype}, got {arg.dtype}"
                    )
                # One .shape per tensor: reused for the positivity check, the rank check,
                # the constant-dimension checks and this parameter's slice of the dynamic
                # ABI tail.
                shape = arg.shape
                if len(shape) != rank:
                    raise InvalidType(
                        f"arg[{index}] '{name}': rank mismatch — expected {rank}D, got {len(shape)}D"
                    )
                # Sub-byte dtype: torch reported the packed uint8 storage, so scale the
                # innermost axis back to elements (see _pack_factor). Packing does not
                # change the rank, so the check above reads either shape the same way.
                if pack != 1 and rank:
                    shape = tuple(shape[:-1]) + (shape[-1] * pack,)
                # The compile path rejects a non-positive runtime dimension inside the
                # shape-policy bind (_validate_positive_int). A cache hit skips that bind
                # entirely, so without this a zero-sized tensor would raise on the launch
                # that compiled the kernel and be accepted by every launch after it. One
                # C-level pass over the torch.Size already in hand; `rank` guards the
                # 0-d case, where min() would see an empty sequence.
                if rank and min(shape) <= 0:
                    raise InvalidShape(
                        f"arg[{index}] '{name}': runtime dimensions must be positive, got {tuple(shape)}"
                    )
                for dim, expected in consts:
                    if shape[dim] != expected:
                        raise InvalidType(
                            f"arg[{index}] '{name}': dim[{dim}] mismatch — "
                            f"expected {expected}, got {shape[dim]}"
                        )
                for dim in dyn_dims:
                    dyn_values.append(shape[dim])
            append(arg.data_ptr())

        for var_name, where in dyn_checks:
            first = -1
            for param_index, dim, pack_mult in where:
                other = args[param_index]
                if other is None:
                    continue
                # pack_mult is 1 unless this is a sub-byte parameter's packed axis.
                actual = other.shape[dim] * pack_mult
                if first < 0:
                    first = actual
                elif actual != first:
                    raise InvalidShape(
                        f"arg[{param_index}] '{slots[param_index][2]}': dynamic shape variable "
                        f"'{var_name}' mismatch — previously {first}, got {actual} at dim[{dim}]"
                    )
        abi_args.extend(dyn_values)

        if stream is None:
            stream = torch.npu.current_stream()
        # Python integers can exceed the uint32_t launch ABI. Saturate the request
        # before ctypes conversion so a large request cannot wrap to zero (0 is the
        # native auto sentinel) and is rejected by the native limit check instead.
        if block_dim > 0xFFFFFFFF:
            block_dim = 0xFFFFFFFF
        _set_dump_info(compiled, args, block_dim)
        # Resolve limits and launch in one C call, avoiding two torch_npu C-extension
        # calls and Python dict/loop work. Errors return before any device launch.
        actual_block_dim = call_kernel(block_dim, stream._as_parameter_, *abi_args)
        if actual_block_dim < 0:
            raise RuntimeFailure(_launch_error_message(actual_block_dim, block_dim, compiled))
        # The capture probe only feeds these two log lines; skip it when neither can emit.
        if logger.isEnabledFor(logging.INFO):
            try:
                import torch_npu

                if torch_npu.npu.is_current_stream_capturing():
                    logging.info(
                        "Capture status [1], kernel launching in graph capture mode (block_dim=%d)", actual_block_dim
                    )
                else:
                    logging.debug("Capture status [0], kernel launching in eager mode (block_dim=%d)", actual_block_dim)
            except (ImportError, AttributeError):
                pass

    entry.lib = lib  # keep the library alive for as long as the closure is reachable
    return entry


